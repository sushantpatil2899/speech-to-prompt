import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Marks key events this app posts, so its own event tap can ignore them.
public enum SyntheticEvent {
    /// Written into each posted event's `eventSourceUserData` field ("STP!").
    public static let tag: Int64 = 0x5354_5021
}

/// Inserts text into the focused field of the frontmost app:
/// 1. snapshot the clipboard (every item, every type)
/// 2. put the text on the clipboard, marked transient/concealed so clipboard managers skip it
/// 3. post ⌘V (needs the Accessibility permission)
/// 4. after a short delay, restore the snapshot, unless something else changed the clipboard
@MainActor
public final class Paster {
    public enum Outcome: Equatable, Sendable {
        /// ⌘V was sent.
        case pasted
        /// The text was left on the clipboard instead (the reason says why).
        case copiedOnly(String)
    }

    /// See AppConfig.pasteRestoreDelaySeconds.
    public var restoreDelay: Double = 0.35

    private typealias ItemSnapshot = [(type: NSPasteboard.PasteboardType, data: Data)]
    private struct PendingRestore {
        var snapshot: [ItemSnapshot]
        var changeCount: Int
        var task: Task<Void, Never>
    }
    private var pending: PendingRestore?

    /// nspasteboard.org conventions: clipboard managers and history tools ignore these items.
    private static let markerTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    public init() {}

    public static var canPaste: Bool { AXIsProcessTrusted() }

    /// - Parameter autoPaste: false = only put the text on the clipboard (no ⌘V, no restore).
    public func insert(_ text: String, autoPaste: Bool = true) -> Outcome {
        let pb = NSPasteboard.general

        // If our previous paste's restore hasn't run yet, the clipboard still holds our text;
        // keep the user's real clipboard from back then as the thing to restore.
        let original: [ItemSnapshot]
        if let p = pending, pb.changeCount == p.changeCount {
            p.task.cancel()
            original = p.snapshot
        } else {
            pending?.task.cancel()
            original = Self.snapshot(pb)
        }
        pending = nil

        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if autoPaste {
            for marker in Self.markerTypes { item.setData(Data(), forType: marker) }
        }
        pb.writeObjects([item])

        guard autoPaste else { return .copiedOnly("auto-paste is off") }
        guard Self.canPaste else {
            // Without Accessibility we can't send ⌘V. Leave the text on the clipboard so the
            // user can paste it themselves (their previous clipboard is not restored).
            return .copiedOnly("Accessibility permission missing")
        }

        Self.postCommandV()
        let count = pb.changeCount
        let delay = restoreDelay
        let task = Task { @MainActor [weak self] in
            try? await Task.sleep(nanoseconds: UInt64(delay * 1_000_000_000))
            guard !Task.isCancelled else { return }
            self?.restoreIfUnchanged()
        }
        pending = PendingRestore(snapshot: original, changeCount: count, task: task)
        return .pasted
    }

    private func restoreIfUnchanged() {
        guard let p = pending else { return }
        pending = nil
        let pb = NSPasteboard.general
        // The user (or an app) copied something new in the meantime: keep that.
        guard pb.changeCount == p.changeCount else { return }
        pb.clearContents()
        let items: [NSPasteboardItem] = p.snapshot.map { snap in
            let item = NSPasteboardItem()
            for entry in snap { item.setData(entry.data, forType: entry.type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    private static func snapshot(_ pb: NSPasteboard) -> [ItemSnapshot] {
        (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type: type, data: $0) } }
        }
    }

    /// Posts ⌘V with only the Command flag set, so a modifier you're still holding
    /// (e.g. the Option hotkey) can't turn it into ⌥⌘V.
    static func postCommandV() {
        postKey(CGKeyCode(kVK_ANSI_V), flags: .maskCommand)
    }

    /// Posts ⌘Z (used by the raw/clean toggle in stage 3).
    static func postCommandZ() {
        postKey(CGKeyCode(kVK_ANSI_Z), flags: .maskCommand)
    }

    private static func postKey(_ key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        else { return }
        for event in [down, up] {
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: SyntheticEvent.tag)
        }
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }
}
